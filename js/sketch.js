function drawPatternFromPoints() {
  const size = windowWidth < 900 ? 2 : 3;
  noStroke();
  fill("#00f9ff");

  for (let i = 0; i < disegnoiniziale.length; i++) {
    const p = disegnoiniziale[i];

    for (let s = 0; s < symmetry; s++) {
      push();
      rotate(s * angle);
      ellipse(p.x, p.y, size, size);
      pop();
    }
  }
}

function savePointToDrawing(x, y) {
  if (x !== xPallinoPrecedente || y !== yPallinoPrecedente) {
    disegnoiniziale.push({ x, y });
    disegnoiniziale.push({ x, y: -y });
    xPallinoPrecedente = x;
    yPallinoPrecedente = y;
  }
}

function drawLivePoint(x, y, save = false) {
  const size = windowWidth < 900 ? 2 : 4;
  noStroke();
  fill("#00f9ff");

  for (let i = 0; i < symmetry; i++) {
    push();
    rotate(i * angle);
    ellipse(x, y, size, size);

    push();
    scale(1, -1);
    ellipse(x, y, size, size);
    pop();

    pop();
  }

  if (save) {
    savePointToDrawing(x, y);
  }
}

function setup() {
  if (windowWidth < 600) {
    createCanvas(windowWidth, windowHeight - 47); //28 dimensione footer che adesso è nascosto
  } else if (windowWidth < 1024) {
    createCanvas(windowWidth, windowHeight - 52.5); // 35 dimensione footer che adesso è nascosto
  } else {
    createCanvas(windowWidth, windowHeight - 55); // togli dimensione header e footer -- 42 dimensione footer che adesso è nascosto
  }

  angleMode(DEGREES);

  

  // inizializzo smoothing con il mouse
  smoothX = mouseX;
  smoothY = mouseY;
}

function draw() {
  push();
  translate(width / 2, height / 2); // sposto l'origine al centro del canvas

  if(mouseX !== pmouseX || mouseY !== pmouseY){
    mouseMovedOnce = true;
  }

  if (!mouseMovedOnce) {
    drawPatternFromPoints();
    mouseMove = 1;
  }else if (mouseMovedOnce && mouseMove === 1) {
    push();
    clear();
    mouseMovedOnce = false;
    mouseMove = 2;
    pop();
  }

  if (mouseX > 0 && mouseX < width && mouseY > 0 && mouseY < height) {
    if (mouseX !== mouseXPrev || mouseY !== mouseYPrev) {
      mouseXPrev = mouseX;
      mouseYPrev = mouseY;
      disegnoiniziale = [];
    }

    // ammorbidisco le coordinate con lerp
    smoothX = lerp(smoothX, mouseX, 0.4);
    smoothY = lerp(smoothY, mouseY, 0.4);

    // coordinate relative al centro
    let dotX = round(smoothX - width / 2);
    let dotY = round(smoothY - height / 2);

    if (windowWidth < 900) {
      drawLivePoint(dotX, dotY, false);
    } else if (!mouseIsPressed) {
      drawLivePoint(dotX, dotY, true);
    }
  }

  pop();
}

function windowResized() {
  setup();
}

